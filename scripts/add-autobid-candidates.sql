-- Auto-bid, the server decides what is queued (docs/AUTOBID_PLAN.md, phase 1).
-- Run once in the Supabase SQL editor, after add-autobid-to-resume-db.sql. Safe to run again.
--
-- Row-level security on and no policy, like every other table: only the server's
-- service-role key reads or writes them.

-- Every job Live found for a profile, and what the server decided about it.
--   found     posted, not screened yet (waiting for its job description)
--   skipped   the rule check or the AI fit check said no; reason says why
--   passed    passed both checks, waiting for room in the queue (newest first)
--   queued    sent to AutoGen; application_id is the Resume DB row
--   expired   passed the checks but no room before it was too old
CREATE TABLE IF NOT EXISTS public.autobid_candidates (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
  profile_id      bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  url_key         text NOT NULL,           -- canonical apply link: one row per job and profile
  job_link        text NOT NULL,
  job_title       text NOT NULL DEFAULT '',
  company         text NOT NULL DEFAULT '',
  site            text NOT NULL DEFAULT '', -- Greenhouse, Lever, Ashby, …
  source          text NOT NULL DEFAULT '', -- hiringcafe, jobright
  posted_at       timestamptz,             -- as the source states it; null when it does not
  found_at        timestamptz NOT NULL DEFAULT now(),
  status          text NOT NULL DEFAULT 'found',
  reason          text NOT NULL DEFAULT '',
  fit_score       real,                    -- 0–100 from the AI fit check
  fit             jsonb,                   -- the check's verdict, blockers and evidence
  job_description text,                    -- only for jobs that passed the rule check
  application_id  bigint REFERENCES public.resume_db_applications(id) ON DELETE SET NULL,
  decided_at      timestamptz,
  UNIQUE (user_id, profile_id, url_key)
);

DO $$
BEGIN
  ALTER TABLE public.autobid_candidates DROP CONSTRAINT IF EXISTS autobid_candidates_status_check;
  ALTER TABLE public.autobid_candidates
    ADD CONSTRAINT autobid_candidates_status_check
    CHECK (status IN ('found', 'skipped', 'passed', 'queued', 'expired'));
END $$;

CREATE INDEX IF NOT EXISTS autobid_candidates_user_found_idx
  ON public.autobid_candidates (user_id, found_at DESC);

CREATE INDEX IF NOT EXISTS autobid_candidates_user_status_idx
  ON public.autobid_candidates (user_id, status, posted_at DESC);

ALTER TABLE public.autobid_candidates ENABLE ROW LEVEL SECURITY;

-- One row per machine doing the work: each JobStrike panel and each AutoGen
-- reports here about once a minute, so several can be shown and none hides another.
CREATE TABLE IF NOT EXISTS public.autobid_workers (
  user_id      uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
  instance_id  text NOT NULL,
  kind         text NOT NULL CHECK (kind IN ('panel', 'autogen')),
  reported_at  timestamptz NOT NULL DEFAULT now(),
  status       jsonb NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (user_id, instance_id)
);

ALTER TABLE public.autobid_workers ENABLE ROW LEVEL SECURITY;

-- When the job was posted, for newest-first order and the 24-hour freshness rule.
-- Null for rows queued by hand: their created_at stands in.
ALTER TABLE public.resume_db_applications
  ADD COLUMN IF NOT EXISTS posted_at timestamptz;

-- A queued row that was never sent before it was too old.
DO $$
BEGIN
  ALTER TABLE public.resume_db_applications
    DROP CONSTRAINT IF EXISTS resume_db_applications_bid_state_check;
  ALTER TABLE public.resume_db_applications
    ADD CONSTRAINT resume_db_applications_bid_state_check
    CHECK (bid_state IN ('none', 'bidding', 'submitted', 'needs_you', 'failed', 'expired'));
END $$;

-- Daily: candidates older than 7 days and workers silent for a day are removed.
-- Needs the pg_cron extension (Supabase → Database → Extensions).
SELECT cron.unschedule('jobstrike-autobid-purge')
WHERE EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'jobstrike-autobid-purge');

SELECT cron.schedule(
  'jobstrike-autobid-purge',
  '17 4 * * *',
  $$
  DELETE FROM public.autobid_candidates WHERE found_at < now() - interval '7 days';
  DELETE FROM public.autobid_workers WHERE reported_at < now() - interval '1 day';
  $$
);
